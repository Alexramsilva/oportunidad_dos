window_ma = 10
elasticidad = 1.5

# -----------------------------------------------------
# FUNCIÓN PRINCIPAL
# -----------------------------------------------------
def analizar_ticker(ticker):
    try:
        df = yf.download(
            ticker,
            period="2y",
            interval="1d",
            auto_adjust=True,
            progress=False
        )
    except Exception:
        return None

    if df is None or df.empty or len(df) < window_ma + 10:
        return None

    # FIX MultiIndex
    if isinstance(df.columns, pd.MultiIndex):
        df.columns = df.columns.get_level_values(0)

    if "Close" not in df.columns:
        return None

    # Medias móviles
    df["MA5"] = df["Close"].rolling(5).mean()
    df["MA10"] = df["Close"].rolling(window_ma).mean()
    df.dropna(inplace=True)

    if df.empty:
        return None

    # Modelo Hooke
    df["x"] = df["Close"] - df["MA10"]
    threshold = df["x"].std() * elasticidad

    if threshold <= 0 or np.isnan(threshold):
        return None

    x_actual = df["x"].iloc[-1]

    # 🔴 SOLO EXTENSIONES BAJISTAS
    if x_actual >= 0:
        return None

    # Tendencia previa bajista (condición de pre-entry)
    tendencia_ok = df["MA5"].iloc[-1] < df["MA10"].iloc[-1]
    if not tendencia_ok:
        return None

    # Margen de oportunidad (qué tan lejos está del entry)
    margen_oportunidad = abs(x_actual) / threshold

    return {
        "Ticker": ticker,
        "Precio actual": float(df["Close"].iloc[-1]),
        "x actual": float(x_actual),
        "Umbral": float(threshold),
        "Margen_Oportunidad": float(margen_oportunidad)
    }

